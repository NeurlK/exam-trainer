const LANG_KEY = 'examTrainer.lang';
let lang = 'ka';
try {
  if (localStorage.getItem(LANG_KEY) === 'en') lang = 'en';
} catch { /* storage unavailable: default to Georgian */ }

export const getLang = () => lang;

export function setLang(next) {
  lang = next;
  document.documentElement.lang = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* ignore */ }
}

export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

// A data field that is either plain text or {ka, en}.
export const loc = v => (v && typeof v === 'object' ? v[lang] ?? v.en : v);

// question.question_ka / question_en, module.name_ka / name_en, …
export const field = (obj, name) => obj?.[`${name}_${lang}`] ?? obj?.[`${name}_en`] ?? '';

export const optionLetter = i => (lang === 'ka' ? 'აბგდ' : 'ABCD')[i] ?? String(i + 1);

export const locale = () => (lang === 'ka' ? 'ka-GE' : 'en-GB');
